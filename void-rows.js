/* ══════════════════════════════════════════════════════════════════
   صفوفٌ أُبطِلت — لأنّ المفتاحَ يُدخِل ويقرأ ولا يحذف
   ══════════════════════════════════════════════════════════════════
   مفتاحُ Supabase المنشورُ عندنا يُدخِل ويقرأ، ولا يحذف ولا يُعدِّل:
   جُرِّب الحذفُ في ٢٥ نوفمبرَ ٢٠٢٦ على صفٍّ بعينِه فأجاب الخادمُ
   HTTP 200 ومصفوفةً فارغةً — صفرُ صفوفٍ تأثّرت — والصفُّ باقٍ كما هو.
   فالإبطالُ من جهةِ الموقعِ لا من جهةِ القاعدة.

   وهذا أسلمُ من المحوِ لو كان ممكنًا: الصفُّ باقٍ ومعه سببُ إبطالِه
   مكتوبًا، فمن قرأ البياناتَ بعدَ سنةٍ عرف لِمَ سقط ولم يظنَّه ضائعًا.
   والسابقةُ في report-rules.js: قائمةُ SKIP لمحاولةِ حسنٍ في الشاملِ
   (طلبُ الأب، ١٠ سبتمبر ٢٠٢٦) — غير أنّ تلك بالتاريخِ واسمِ الاختبار،
   وهذه بالمحاولةِ بعينِها فلا تُسقِط معها غيرَها.

   ⚠️ والمفتاحُ meta.pid لا رقمُ الصفِّ (id): قراءاتُ practice.html
   تطلب meta وحدَها («select=meta»)، فالإبطالُ بالرقمِ لا يَبلغها —
   وتبقى الورقةُ المبطَلةُ تحسب في لافتةِ النموذجِ الكاملِ وفي عدِّ
   ما عُرِض (SeenCap). ومن لا pid له (وهي الصفوفُ القديمةُ) يُبطَل
   برقمِه، وكلاهما مقبولٌ هنا.

   ولا يُزاد في هذه القائمةِ شيءٌ إلّا بطلبِ الأبِ صريحًا على صفٍّ
   بعينِه: ليست مكانًا لإخفاءِ درجةٍ لم تَسُرّ.
   ══════════════════════════════════════════════════════════════════ */
(function(g){

  g.VOID_ROWS = {
    /* طلبُ الأبِ (٢٥ نوفمبرَ ٢٠٢٦): «احذف آخر اختبار الدرجة ٤٥ من ٦٤
       — أنا الي مختبر». وهو بيّنٌ في الأرقامِ أيضًا: ٣١١٦ ثانيةً
       (اثنتان وخمسون دقيقة) وصفرُ إجاباتٍ متسرّعة، وفهدٌ لم يُجلس
       ورقةً بهذا التأنّي في تاريخِه كلِّه — أطولُ ورقةٍ له قبلَها
       ٧٧٣ ثانيةً. ولو حُسِبت لرفعت معدَّلَه بما ليس من عملِه، ولصعّدت
       طولَ ورقتِه القادمةِ على جهدٍ لم يبذله. */
    "mwwhm452_4iabfi":
      "فهد · STEP — نموذج كامل · ٤٥/٦٤ · ٢٥ نوفمبر ٢٢:٥١ — جلسها الأبُ نفسُه لا الولد"
  };

  function keyOf(row){
    var V = g.VOID_ROWS || {};
    if(!row) return "";
    var m = row.meta || row;
    if(m && m.pid && V[m.pid]) return m.pid;
    if(m && m.cid && V[m.cid]) return m.cid;
    if(row.id && V[row.id]) return row.id;
    return "";
  }

  g.VoidRows = {
    /* هل أُبطِل هذا الصفّ؟ يقبل صفًّا كاملًا ({meta:…}) أو meta وحدَها،
       لأنّ بعضَ القراءاتِ تُمرّر هذه وبعضُها تلك. */
    is: function(row){ return !!keyOf(row); },
    why: function(row){ var k = keyOf(row); return k ? (g.VOID_ROWS[k] || "") : ""; },
    /* يُمرَّر دالّةً مباشرةً إلى then، فلا يستعمل this */
    strip: function(rows){
      if(!Array.isArray(rows)) return rows;
      return rows.filter(function(r){ return !keyOf(r); });
    },
    /* عددُ ما أُبطِل — يُقال في التقريرِ فلا يختفي عملٌ بلا بيان */
    count: function(rows){
      if(!Array.isArray(rows)) return 0;
      var n = 0;
      rows.forEach(function(r){ if(keyOf(r)) n++; });
      return n;
    }
  };

})(window);
