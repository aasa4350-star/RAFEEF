function gMatrixNum(){
  var r1=[ri(2,9),ri(2,9)], r2=[ri(2,9),ri(2,9)], r3=[ri(2,9),ri(2,9)];
  var mode=gp(["sum","prod","diff"]);
  var RULES = { sum:function(x,y){return x+y;}, prod:function(x,y){return x*y;}, diff:function(x,y){return Math.abs(x-y);} };
  var f=RULES[mode];
  var nm = mode==="sum" ? "مجموعُهما" : mode==="prod" ? "حاصلُ ضربهما" : "الفرقُ بينهما";
  var c1=f(r1[0],r1[1]), c2=f(r2[0],r2[1]), c3=f(r3[0],r3[1]);
  if(c1===c2) return null;
  /* ألّا تتّسق قاعدةٌ أخرى مع الصفّين، وإلّا صار للسؤال جوابان */
  for(var k_ in RULES){
    if(k_===mode) continue;
    if(RULES[k_](r1[0],r1[1])===c1 && RULES[k_](r2[0],r2[1])===c2) return null;
  }
  return Q("<b>مصفوفة:</b> في كلّ صفٍّ علاقةٌ واحدة — ما المفقود؟<br>"+
    L(r1[0]+" | "+r1[1]+" | "+c1)+"<br>"+L(r2[0]+" | "+r2[1]+" | "+c2)+"<br>"+
    L(r3[0]+" | "+r3[1]+" | ؟"),
    c3, [c3+1, r3[0]+r3[1]===c3 ? r3[0]*r3[1] : r3[0]+r3[1], Math.abs(r3[0]-r3[1])===c3 ? c3+2 : Math.abs(r3[0]-r3[1])],
    "افحص الصفَّ الأوّل: "+r1[0]+" و"+r1[1]+" ← "+c1+" أي "+nm+". "+
    "وتحقّق بالثاني: "+r2[0]+" و"+r2[1]+" ← "+c2+" ✔. فالثالث: "+r3[0]+" و"+r3[1]+" ← "+c3+". "+
    "ولا تحكم بقاعدةٍ من صفٍّ واحد — تحقّقْ منها بصفٍّ ثانٍ أوّلًا.");
}

