function opt4(correct, ds){
  var out=[String(correct)], seen={}; seen[String(correct)]=1;
  for(var i=0;i<ds.length && out.length<4;i++){
    var k=String(ds[i]);
    if(k==="undefined"||k==="null"||k==="NaN"||k===""||seen[k]) continue;
    seen[k]=1; out.push(k);
  }
  return out.length===4 ? out : null;
}
function Q(stem, correct, ds, expl){
  var o=opt4(correct, ds);
  return o ? [stem, o, 0, expl] : null;
}

