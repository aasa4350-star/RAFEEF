var NONCE = ["الفراهيد","الزمازم","البلانق","الهواتر","الصلاهب","الدواهم","القراميد","النواظم","الشهابر","الملازم"];

/* مقدّمةٌ غير واقعية: «كلّ أ ب، وكلّ ب ج» ⟸ «كلّ أ ج» قطعًا.
   والمشتّتاتُ عكسُ النتيجة، وتعميمٌ على ج كلِّها، ونفيٌ لا يلزم. */
function gSyllogism(){
  var w=pick(NONCE,3), A=w[0], B=w[1], C=w[2];
  return Q("<b>مقدّمة غير واقعية:</b> «كلّ "+A+" "+B+"» و«كلّ "+B+" "+C+"». "+
    "ما الاستنتاج الذي يلزم منطقيًّا — بغضّ النظر عن الواقع؟",
    "كلّ "+A+" "+C,
    ["كلّ "+C+" "+A, "بعض "+A+" ليست "+C, "لا شيء ممّا سبق يلزم"],
    "السلسلة تمضي في اتّجاهٍ واحد: ما دام كلُّ "+A+" داخلًا في "+B+"، وكلُّ "+B+" داخلًا في "+C+
    "، فكلُّ "+A+" داخلٌ في "+C+" ضرورةً. أمّا عكسُها («كلّ "+C+" "+A+"») فلا يلزم — "+
    "فقد يكون في "+C+" ما ليس من "+A+". والمصيدةُ أن تَردَّ المقدّمةَ لأنّها غيرُ واقعية، "+
    "والمطلوبُ اتّباعُ المنطق لا الواقع.");
}

/* «بعض» لا تُعكَس إلى «كلّ»: من «كلّ أ ب» و«بعض ب ج» لا يلزم شيءٌ عن أ. */
function gSomeTrap(){
  var w=pick(NONCE,3), A=w[0], B=w[1], C=w[2];
  return Q("<b>مقدّمة غير واقعية:</b> «كلّ "+A+" "+B+"» و«بعض "+B+" "+C+"». ما الذي يلزم؟",
    "لا يلزم شيءٌ عن علاقة "+A+" بـ"+C,
    ["كلّ "+A+" "+C, "بعض "+A+" "+C, "لا شيء من "+A+" "+C],
    "«بعض "+B+" "+C+"» قد يصدق على الجزء الذي ليس فيه "+A+" أصلًا. فلا يلزم أنّ شيئًا من "+A+
    " هو "+C+"، ولا يلزم نفيُه. والمصيدةُ أن يقفز الذهنُ من «بعض» إلى حكمٍ جازم — "+
    "وفي المنطق: ما لا يلزم لا يُقال.");
}

/* متتابعةٌ بقاعدتين متناوبتين — الذهنُ يبحث عن قاعدةٍ واحدة فيتعثّر */
function gAltRule(){
  var a=ri(2,9), m=gp([2,3]), p=ri(3,9);
  var s=[a]; for(var i=0;i<5;i++) s.push(i%2===0 ? s[i]*m : s[i]+p);
  var nx = s.length%2===1 ? s[5]*m : s[5]+p;   /* الحدّ السابع */
  return Q("<b>مرونة:</b> أكمل المتتابعة: "+L(s.join("، "))+"، ؟",
    nx, [s[5]+m, s[5]*p, nx+p],
    "ليست قاعدةً واحدة بل قاعدتان تتناوبان: نضرب في "+m+" ثمّ نزيد "+p+" ثمّ نضرب ثمّ نزيد. "+
    "فمن "+s[0]+": ×"+m+" = "+s[1]+"، +"+p+" = "+s[2]+"، ×"+m+" = "+s[3]+"، +"+p+" = "+s[4]+
    "، ×"+m+" = "+s[5]+"، ثمّ +"+p+" = "+nx+". ومتى فشلت قاعدةٌ واحدةٌ فجرّب التناوب.");
}

/* تناظرٌ عدديٌّ: العلاقةُ نفسُها لا العددُ نفسُه */
function gNumAnalogy(){
  var k=ri(2,6), c=ri(1,9), a=ri(2,12), b=ri(2,12);
  if(a===b) return null;
  var fa=a*k+c, fb=b*k+c;
  return Q("<b>تناظر عددي:</b> "+L(a+" ← "+fa)+" فإنّ "+L(b+" ← ؟"),
    fb, [b*k, b+(fa-a), fb+k],
    "نبحث عن العلاقة لا عن العدد: "+fa+" = ("+a+" × "+k+") + "+c+". "+
    "فنطبّقها على الثاني: ("+b+" × "+k+") + "+c+" = "+fb+". "+
    "والمصيدةُ أن تأخذ الفرقَ ("+(fa-a)+") وتضيفه — وهو يصدق على المثال الأوّل ولا يصدق على الثاني.");
}

/* الشاذّ بمعيارٍ غير المعيار المألوف */
function gOddShift(){
  var sets = [
    { odd:"٢٦", rest:["١٦","٣٦","٤٩"], why:"١٦ = ٤² و٣٦ = ٦² و٤٩ = ٧² — مربّعاتٌ كاملة. و٢٦ ليس مربّعًا كاملًا (بين ٢٥ و٣٦). والمعيارُ هنا ليس الزوجيّةَ ولا آخرَ رقمٍ بل كونُه مربّعًا." },
    { odd:"٢٣", rest:["١٥","٢١","٣٥"], why:"١٥ = ٣×٥ و٢١ = ٣×٧ و٣٥ = ٥×٧ — كلُّها حاصلُ ضربِ عددين أوّليّين فرديّين. و٢٣ عددٌ أوّليٌّ لا يتحلّل." },
    { odd:"القمر", rest:["المرّيخ","الزهرة","عطارد"], why:"المرّيخُ والزهرةُ وعطاردُ كواكبُ تدور حول الشمس، والقمرُ تابعٌ يدور حول الأرض." },
    { odd:"الأكسجين", rest:["الماء","الملح","السكّر"], why:"الماءُ والملحُ والسكّرُ مركّباتٌ تتّحد فيها عناصر، والأكسجينُ عنصرٌ مفرد." },
    { odd:"السمع", rest:["العين","الأذن","الأنف"], why:"العينُ والأذنُ والأنفُ أعضاءٌ، والسمعُ حاسّةٌ — أي وظيفةٌ لا عضو." },
    { odd:"١١", rest:["٢١","٣٣","٥١"], why:"كلُّها من رقمين ومجموعُ رقميها يقبل القسمة على ٣ عدا ١١، والأدقّ: ٢١ و٣٣ و٥١ تقبل القسمة على ٣، و١١ عددٌ أوّليّ لا يقبلها." },
    { odd:"الدقيقة", rest:["المتر","الجرام","اللتر"], why:"المتر والجرام واللتر وحداتُ قياسٍ للمادّة (طولٌ وكتلةٌ وحجم)، والدقيقةُ وحدةُ زمن." },
    { odd:"البخار", rest:["الثلج","الحديد","الخشب"], why:"الثلجُ والحديدُ والخشبُ موادُّ صلبة، والبخارُ غاز." },
    { odd:"المجهر", rest:["النظّارة","المنظار","العدسة"], why:"كلُّها تعتمد العدسات، لكنّ النظّارةَ والمنظارَ والعدسةَ تُعين العينَ على ما تراه أصلًا، والمجهرَ يُري ما لا تراه العينُ البتّة." }
  ];
  var s=gp(sets);
  return Q("<b>الشاذّ:</b> أيُّ هذه لا ينتمي إلى المجموعة؟", s.odd, s.rest, s.why);
}

/* ترتيبٌ من علاقاتٍ متفرّقة — يلزم بناءُ السلسلة كاملةً قبل الجواب */
function gOrderChain(){
  var nm=pick(["سعد","ناصر","خالد","فيصل","ماجد","بدر"],4);
  /* الترتيب الحقيقي: nm[0] الأطول ← nm[3] الأقصر */
  var facts = shuf([
    nm[0]+" أطولُ من "+nm[1],
    nm[1]+" أطولُ من "+nm[2],
    nm[2]+" أطولُ من "+nm[3]
  ]);
  var ask = gp(["الأطول","الأقصر"]);
  var ans = ask==="الأطول" ? nm[0] : nm[3];
  var ds  = ask==="الأطول" ? [nm[1],nm[2],nm[3]] : [nm[2],nm[1],nm[0]];
  return Q("<b>ترتيب:</b> "+facts.join("، و")+". فمَن <b>"+ask+"</b>؟",
    ans, ds,
    "رتّب السلسلة كاملةً قبل أن تجيب: "+nm[0]+" > "+nm[1]+" > "+nm[2]+" > "+nm[3]+
    ". فالأطولُ "+nm[0]+" والأقصرُ "+nm[3]+". والمصيدةُ أن تُجيب من أوّل جملةٍ قرأتها.");
}

/* قاعدةٌ تتبدّل: المدخلاتُ نفسُها والمخرجُ يختلف */
function gRuleSwitch(){
  var a=ri(3,12), b=ri(2,9);
  var r1=a+b, r2=a*b, r3=a-b;
  return Q("<b>تبديل قاعدة:</b> إذا كان "+L("أ ★ ب = (أ × ب) − (أ + ب)")+
    "، فكم يساوي "+L(a+" ★ "+b)+" ؟",
    S(r2-r1), [S(r2+r1), S(r1-r2), S(r2), S(r3)],
    "العمليّةُ معرَّفةٌ لا معروفة، فاتّبع تعريفَها حرفًا بحرف: "+
    "(أ × ب) = "+a+" × "+b+" = "+r2+"، و(أ + ب) = "+a+" + "+b+" = "+r1+
    "، والفرق: "+r2+" − "+r1+" = "+(r2-r1)+". "+
    "والمصيدةُ أن يسبق الذهنُ إلى عمليّةٍ يعرفها بدل التي عُرِّفت له.");
}

/* مصفوفةٌ عدديّة: القاعدةُ في الصفّ تُستخرج ثمّ تُطبَّق */
function gMatrixNum(){
  var r1=[ri(2,9),ri(2,9)], r2=[ri(2,9),ri(2,9)], r3=[ri(2,9),ri(2,9)];
  var mode=gp(["sum","diff","prod"]);
  var f = mode==="sum" ? function(x,y){return x+y;} : mode==="prod" ? function(x,y){return x*y;}
        : function(x,y){return Math.abs(x-y);};
  var nm = mode==="sum" ? "مجموعُ العددين" : mode==="prod" ? "حاصلُ ضربهما" : "الفرقُ بينهما";
  var c1=f(r1[0],r1[1]), c2=f(r2[0],r2[1]), c3=f(r3[0],r3[1]);
  if(c1===c2) return null;
  /* ألّا تتّسق قاعدةٌ أخرى مع الصفّين المعطيين، وإلّا صار للسؤال جوابان */
  var RULES = { sum:function(x,y){return x+y;}, prod:function(x,y){return x*y;}, diff:function(x,y){return Math.abs(x-y);} };
  for(var k_ in RULES){
    if(k_===mode) continue;
    if(RULES[k_](r1[0],r1[1])===c1 && RULES[k_](r2[0],r2[1])===c2) return null;
  }
  return Q("<b>مصفوفة:</b> في كلّ صفٍّ علاقةٌ واحدة — ما العدد المفقود؟<br>"+
    L(r1[0]+" | "+r1[1]+" | "+c1)+"<br>"+L(r2[0]+" | "+r2[1]+" | "+c2)+"<br>"+
    L(r3[0]+" | "+r3[1]+" | ؟"),
    c3, [c3+1, r3[0]+r3[1]===c3 ? r3[0]*r3[1] : r3[0]+r3[1], Math.abs(r3[0]-r3[1])===c3 ? c3+2 : Math.abs(r3[0]-r3[1])],
    "افحص الصفَّ الأوّل: "+r1[0]+" و"+r1[1]+" ينتج عنهما "+c1+" — أي "+nm+". "+
    "وتحقّق بالصفّ الثاني: "+r2[0]+" و"+r2[1]+" ← "+c2+" ✔. "+
    "فطبّقها على الثالث: "+r3[0]+" و"+r3[1]+" ← "+c3+". "+
    "ولا تحكم بقاعدةٍ من صفٍّ واحد — تحقّقْ منها بصفٍّ ثانٍ قبل أن تطبّقها.");
}

