"use strict";

function ri(a,b){ return Math.floor(Math.random()*(b-a+1))+a; }
function gp(a){ return a[Math.floor(Math.random()*a.length)]; }
function shuf(a){ for(var i=a.length-1;i>0;i--){ var j=Math.floor(Math.random()*(i+1)); var t=a[i]; a[i]=a[j]; a[j]=t; } return a; }
function pick(a,n){ return shuf(a.slice()).slice(0,n); }
function gcd(a,b){ a=Math.abs(a); b=Math.abs(b); while(b){ var t=b; b=a%b; a=t; } return a||1; }
function S(n){ return String(n).replace(/-/g,"−"); }   /* سالبٌ يُعرَض ناقصًا حقيقيًّا لا شرطةً */
function L(x){ return '<span dir="ltr" style="unicode-bidi:isolate">'+x+'</span>'; }

/* opt4 — أربعةُ خياراتٍ متمايزة، الصحيحُ أوّلًا. ولو تكرّر مشتّتٌ مع
   الصحيح أُسقِط، ولو نقص العددُ أُرجِع null فيُعاد توليدُ السؤال —
   أسلمُ من إخراج سؤالٍ له جوابان. */
function opt4(correct, ds){
  var out=[String(correct)], seen={}; seen[String(correct)]=1;
  for(var i=0;i<ds.length && out.length<4;i++){
    var k=String(ds[i]);
    if(k==="undefined"||k==="null"||k==="NaN"||k===""||seen[k]) continue;
    seen[k]=1; out.push(k);
  }
  return out.length===4 ? out : null;
}
function Q(stem, correct, ds, expl){
  var o=opt4(correct, ds);
  return o ? [stem, o, 0, expl] : null;
}

