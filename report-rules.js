/* ============================================================
   قواعد عرض الملاحظات في لوحات المتابعة.

   طلب الأب (٢٦ أغسطس ٢٠٢٦): «ملاحظات الخروج من الصفحة تسبّب لي
   إزعاجًا — خلّها ٤٨ ساعة وتختفي. أمّا حفظ الكلمات والمراجعة
   فخلّها أسبوعًا فقط».

   وهو محقّ: الملاحظة إنّما تنفع وهي طريّة — يقرؤها فيسأل ابنه
   اليوم أو غدًا. وبعد ذلك تصير سطرًا أحمر لا يُفعل به شيء، ويزاحم
   ما هو أحدث منه. وكانت جلسةٌ من ١٠ أغسطس ما تزال معلّمةً في
   ٢٦ منه، تحتلّ مكان جلسات هذا الأسبوع.

   وهذه القواعد في ملفٍّ واحد لأنّ أربع صفحاتٍ تعرضها —
   index.html وhome.html وchild.html وreport.html — ونسخُها أربعًا
   يعني أن تُعدَّل واحدةٌ وتبقى ثلاث.

   وما يُخفى هنا هو العرض وحده. حساب المتوسّطات لا يتغيّر: الجلسة
   التي استُبعدت تبقى مستبعَدةً، لأنّ سبب استبعادها لا يبطل بمرور
   يومين. الذي يبطل هو الحاجة إلى تنبيهٍ أحمر عليها.
   ============================================================ */
(function(g){
  var FLAG_HOURS = 48;    /* عمر ملاحظة الخروج/السرعة/عدم الاحتساب */
  var VOCAB_DAYS = 7;     /* مدى جلسات الكلمات المعروضة */

  /* meta.at وقت الجهاز الحقيقيّ، وcreated_at احتياطيٌّ إن غاب.
     وما لا تاريخ له يُعدّ قديمًا فلا تُعرض ملاحظته. */
  function ageMs(row){
    var t = (row && row.meta && row.meta.at) || (row && row.created_at);
    var ms = t ? Date.parse(t) : NaN;
    return isNaN(ms) ? Infinity : (Date.now() - ms);
  }

  g.RR = {
    FLAG_HOURS: FLAG_HOURS,
    VOCAB_DAYS: VOCAB_DAYS,
    ageMs: ageMs,

    /* هل تُعرض ملاحظات هذه الجلسة؟ (خروج · سرعة · غير محتسبة) */
    freshFlag: function(row){ return ageMs(row) <= FLAG_HOURS * 3600e3; },

    /* هل الجلسة داخل مدى أسبوع الكلمات؟ */
    recentVocab: function(row){ return ageMs(row) <= VOCAB_DAYS * 86400e3; },

    /* ═══ متوسّط المحادثة — سؤال الأب (٧ سبتمبر ٢٠٢٦) ═══
       «وش الفرق بين التقريرين ما فهمت»: السطر الأوّل خلاصةُ كلّ الجلسات،
       وما تحته جلساتٌ مفردة. لكنّ الخلاصة نفسها كانت تُضلّل من وجهين:

       ١) النسبتان على أساسين مختلفين. رفيف: النطق متوسّط جلساتها الثمان،
          وصحّة الجملة متوسّط أربعٍ منها فقط — لأنّ الأربع الأخرى جملُها
          قصيرةٌ لم يُحكم على نحوها. والسطر يعرضهما متجاورتين كأنّهما
          على أساسٍ واحد.

       ٢) الجلسة القصيرة تزن مثل الطويلة. جلسةٌ فيها جملةٌ واحدة صفر٪
          كانت تسحب المتوسّط مثل جلسةٍ فيها أربع جملٍ ٧٥٪. فصحّة رفيف
          تظهر ٥٦٪ وهي بالجمل ٦٨٪ — فرقُ اثنتي عشرة نقطة.

       فصار الوزن بعدد الجمل لا بعدد الجلسات، ونُرجع مع النسبة عددَ
       الجمل التي بُنيت عليها ليُعرَض بجانبها.

       والوزن الأدقّ عدد الجمل المُقيَّمة فعلًا (pronN / corrN)، وقد
       أُضيفا إلى ما تحفظه talk.html من اليوم؛ وما قبلهما من صفوفٍ
       قديمةٍ يُوزن بعدد جمل الجلسة، وهو أقرب من المساواة بينها. */
    talkAvg: function(sessions, field, nField){
      var sum = 0, w = 0, sess = 0;
      (sessions || []).forEach(function(s){
        var m = (s && s.meta) || {};
        if (typeof m[field] !== "number") return;
        var n = (typeof m[nField] === "number" && m[nField] > 0) ? m[nField]
              : ((typeof m.turns === "number" && m.turns > 0) ? m.turns : 1);
        sum += m[field] * n; w += n; sess++;
      });
      return w ? { pct: Math.round(sum / w), n: w, sessions: sess } : null;
    }
  };
})(window);
