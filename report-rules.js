/* ============================================================
   قواعد عرض الملاحظات في لوحات المتابعة.

   طلب الأب (٢٦ أغسطس ٢٠٢٦): «ملاحظات الخروج من الصفحة تسبّب لي
   إزعاجًا — خلّها ٤٨ ساعة وتختفي. أمّا حفظ الكلمات والمراجعة
   فخلّها أسبوعًا فقط».

   وهو محقّ: الملاحظة إنّما تنفع وهي طريّة — يقرؤها فيسأل ابنه
   اليوم أو غدًا. وبعد ذلك تصير سطرًا أحمر لا يُفعل به شيء، ويزاحم
   ما هو أحدث منه. وكانت جلسةٌ من ١٠ أغسطس ما تزال معلّمةً في
   ٢٦ منه، تحتلّ مكان جلسات هذا الأسبوع.

   وهذه القواعد في ملفٍّ واحد لأنّ أربع صفحاتٍ تعرضها —
   index.html وhome.html وchild.html وreport.html — ونسخُها أربعًا
   يعني أن تُعدَّل واحدةٌ وتبقى ثلاث.

   وما يُخفى هنا هو العرض وحده. حساب المتوسّطات لا يتغيّر: الجلسة
   التي استُبعدت تبقى مستبعَدةً، لأنّ سبب استبعادها لا يبطل بمرور
   يومين. الذي يبطل هو الحاجة إلى تنبيهٍ أحمر عليها.
   ============================================================ */
(function(g){
  var FLAG_HOURS = 48;    /* عمر ملاحظة الخروج/السرعة/عدم الاحتساب */
  var VOCAB_DAYS = 7;     /* مدى جلسات الكلمات المعروضة */

  /* meta.at وقت الجهاز الحقيقيّ، وcreated_at احتياطيٌّ إن غاب.
     وما لا تاريخ له يُعدّ قديمًا فلا تُعرض ملاحظته. */
  function ageMs(row){
    var t = (row && row.meta && row.meta.at) || (row && row.created_at);
    var ms = t ? Date.parse(t) : NaN;
    return isNaN(ms) ? Infinity : (Date.now() - ms);
  }

  g.RR = {
    FLAG_HOURS: FLAG_HOURS,
    VOCAB_DAYS: VOCAB_DAYS,
    ageMs: ageMs,

    /* هل تُعرض ملاحظات هذه الجلسة؟ (خروج · سرعة · غير محتسبة) */
    freshFlag: function(row){ return ageMs(row) <= FLAG_HOURS * 3600e3; },

    /* هل الجلسة داخل مدى أسبوع الكلمات؟ */
    recentVocab: function(row){ return ageMs(row) <= VOCAB_DAYS * 86400e3; },

    /* ═══ متوسّط المحادثة — سؤال الأب (٧ سبتمبر ٢٠٢٦) ═══
       «وش الفرق بين التقريرين ما فهمت»: السطر الأوّل خلاصةُ كلّ الجلسات،
       وما تحته جلساتٌ مفردة. لكنّ الخلاصة نفسها كانت تُضلّل من وجهين:

       ١) النسبتان على أساسين مختلفين. رفيف: النطق متوسّط جلساتها الثمان،
          وصحّة الجملة متوسّط أربعٍ منها فقط — لأنّ الأربع الأخرى جملُها
          قصيرةٌ لم يُحكم على نحوها. والسطر يعرضهما متجاورتين كأنّهما
          على أساسٍ واحد.

       ٢) الجلسة القصيرة تزن مثل الطويلة. جلسةٌ فيها جملةٌ واحدة صفر٪
          كانت تسحب المتوسّط مثل جلسةٍ فيها أربع جملٍ ٧٥٪. فصحّة رفيف
          تظهر ٥٦٪ وهي بالجمل ٦٨٪ — فرقُ اثنتي عشرة نقطة.

       فصار الوزن بعدد الجمل لا بعدد الجلسات، ونُرجع مع النسبة عددَ
       الجمل التي بُنيت عليها ليُعرَض بجانبها.

       والوزن الأدقّ عدد الجمل المُقيَّمة فعلًا (pronN / corrN)، وقد
       أُضيفا إلى ما تحفظه talk.html من اليوم؛ وما قبلهما من صفوفٍ
       قديمةٍ يُوزن بعدد جمل الجلسة، وهو أقرب من المساواة بينها. */
    /* ═══ خانات الكلمات الثلاث — طلب الأب (٧ سبتمبر ٢٠٢٦) ═══
       «خلّه يبيّن عندي كم كلمة حفظها جديدة، وكم راجعها من القديم، وكم
        راجعها من الجديد. يعني يصير عندي ثلاث خاناتٍ أشوفها».
       وهي أنماط الجلسات الثلاثة نفسها في صفحة القراءة:
         new    📚 كلماتٌ جديدة قُدّمت له أوّل مرّة
         review 🔁 مراجعةٌ من المحفوظ القديم
         fresh  🆕 مراجعةٌ لما حفظه حديثًا ولم يرسخ بعد
       نعدّ الكلمات لا الجلسات، ونستبعد غير الموثوقة كبقيّة الأرقام.
       والصفوف القديمة بلا mode تُحسب مراجعةً — فالمراجعة كانت الأصل قبل
       أن تُفصل الأنماط، وعدّها «جديدًا» يضخّم رقم الحفظ بغير حقّ. */
    VOCAB_MODES: [["new","📚","حفظ جديد"], ["review","🔁","راجع من القديم"], ["fresh","🆕","راجع من الجديد"]],
    vocabModes: function(rows){
      var B = { "new":{w:0,c:0,n:0}, review:{w:0,c:0,n:0}, fresh:{w:0,c:0,n:0} };
      (rows || []).forEach(function(p){
        var m = (p && p.meta) || {};
        if (m.trusted === false) return;
        var k = (m.mode === "new" || m.mode === "fresh") ? m.mode : "review";
        B[k].w += (m.total || 0); B[k].c += (m.correct || 0); B[k].n++;
      });
      return B;
    },
    /* أعلى رقمِ حفظٍ سُجّل — تراكميّ لا يتراجع، ولا تُحتسب فيه جلسةٌ خرج منها */
    vocabLearned: function(rows){
      var L = 0, T = 0;
      (rows || []).forEach(function(p){
        var m = (p && p.meta) || {};
        if (m.trusted === false) return;
        if (typeof m.learned === "number" && m.learned > L) L = m.learned;
        if (typeof m.vocTotal === "number" && m.vocTotal > T) T = m.vocTotal;
      });
      return { learned: L, total: Math.max(T, L) };
    },

    /* ═══ وصفُ الجلسة كما يفهمه الأب ═══
       بلاغه (٨ سبتمبر ٢٠٢٦): «يقول جلست ٨ دقايق وتحدّثت كثيرًا، وما طلع
       لي إلّا ٥ جمل — ودّي توضيح أكثر». وكان التقرير يعرض الجمل المفهومة
       وحدها، فلا يُفرّق بين من لم يتكلّم ومن تكلّم ولم يُفهم، ولا يُظهر
       كم جلس أصلًا. فصار لكلّ جلسةٍ سطرُها: مدّتها، وكم ضغط، وكم لم يُفهم. */
    talkLine: function(meta){
      var m = meta || {}, out = [];
      if (typeof m.secs === "number" && m.secs > 0)
        out.push(m.secs >= 60 ? (Math.floor(m.secs/60) + " د " + (m.secs%60) + " ث") : (m.secs + " ث"));
      if (typeof m.unh === "number" && m.unh > 0)
        out.push("🔁 " + m.unh + " محاولة ما وضحت");
      return out;
    },
    /* ═══ ذكاءٌ أم آليّ؟ — سؤال الأب (٨ سبتمبر ٢٠٢٦) ═══
       «اللي يتكلّم معه ذكاء اصطناعيّ أو آليّ؟» والجواب: الاثنان. الأصل
       نموذجٌ حقيقيّ يقرأ كلام الطفل ويردّ عليه ويحكم على نحو جملته؛ فإن
       تأخّر فوق ٢٨ث أو سقط، نزل البرنامج إلى ردٍّ آليٍّ من قائمةٍ ثابتة.
       ولم يكن أحدٌ يعرف النسبة — لا الأب ولا نحن — فصارت تُقاس وتُعرض:
       aiN ردودُ النموذج · fbN الردودُ الآليّة · aiMs مجموع الانتظار. */
    talkAiSplit: function(sessions){
      var ai = 0, fb = 0, ms = 0;
      (sessions || []).forEach(function(s){
        var m = (s && s.meta) || {};
        if (typeof m.aiN  === "number") ai += m.aiN;
        if (typeof m.fbN  === "number") fb += m.fbN;
        if (typeof m.aiMs === "number") ms += m.aiMs;
      });
      var n = ai + fb;
      return n ? { ai:ai, fb:fb, total:n, pct:Math.round(ai*100/n),
                   avgSec: ms ? Math.round(ms/n/100)/10 : null } : null;
    },
    /* مجموع ما لم يُفهم في مجموعة جلسات — للسطر الأوّل (الخلاصة) */
    talkUnheard: function(sessions){
      var n = 0;
      (sessions || []).forEach(function(s){
        var v = s && s.meta && s.meta.unh;
        if (typeof v === "number") n += v;
      });
      return n;
    },

    talkAvg: function(sessions, field, nField){
      var sum = 0, w = 0, sess = 0;
      (sessions || []).forEach(function(s){
        var m = (s && s.meta) || {};
        if (typeof m[field] !== "number") return;
        var n = (typeof m[nField] === "number" && m[nField] > 0) ? m[nField]
              : ((typeof m.turns === "number" && m.turns > 0) ? m.turns : 1);
        sum += m[field] * n; w += n; sess++;
      });
      return w ? { pct: Math.round(sum / w), n: w, sessions: sess } : null;
    }
  };
})(window);
