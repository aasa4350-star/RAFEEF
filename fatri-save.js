/* ═══ حفظُ الاختبارِ الفتريِّ الناقصِ ═══════════════════════════════
   تشخيصُ سعودٍ في الإنجليزي (١٨ أكتوبر ٢٠٢٦) كشفها: بدأ الفتريَّ ٢٢
   مرّةً وترك خمسَ عشرةَ منها بعد سؤالٍ أو سؤالين — يضغط «اختبار جديد»
   حتّى تعجبه الورقة. وكانت الصفحةُ تَحفظ لكلِّ قُصاصةٍ «٠ من ٢٠»، لأنّ
   المقامَ هو درجةُ الورقةِ كاملةً مهما أجاب. فهبط متوسّطُه المعروضُ
   إلى ٣١٪ وهو في محاولاتِه المكتملةِ ٧٠٪.

   وليست علّةَ الإنجليزيِّ وحدَه: قياسُ القاعدةِ يومَ كُتبت هذا الملفُّ
   أظهر ستّةً من ثلاثةَ عشرَ اختبارًا فتريًّا مظلومةً — رياضيّاتُ سعودٍ
   ٦٧٪ معروضةً و٩٢٪ حقيقيّةً، ورياضيّاتُ أسامةَ ٥٧٪ و٩١٪، ورياضيّاتُ
   رفيفَ ٧١٪ و٩٤٪.

   والقاعدةُ هنا هي قاعدةُ القراءةِ نفسُها في reading.html (٢٥ سبتمبر):
     · أجاب عن الكلّ        ⇐ درجةٌ كاملةٌ كما كانت.
     · أجاب عن ثلاثةٍ فأكثرَ ⇐ درجةٌ من البنودِ التي أجابها هو، لا من
       الورقةِ كلِّها، وتُوسَم partial فيُعرَف أنّها ليست ورقةً تامّة.
     · أجاب عن أقلَّ من ثلاثة ⇐ أثرٌ لا درجة (kind="activity")، فلا
       يدخل متوسّطًا ولا يُسقِطه، ويبقى الخبرُ محفوظًا: فتح وأجاب عن
       بندين ثمّ بدّل. وعتبةُ الثلاثِ لم تكن عبثًا: صفٌّ بدرجة «١ / ١»
       يرفع المتوسّطَ بغير حقٍّ كما يُسقطه «٠ / ٢٠».

   ولِمَ ملفٌّ واحدٌ لا سطرٌ في كلِّ صفحة: الصفحاتُ إحدى عشرةَ ولها
   ثلاثةَ عشرَ موضعَ حفظ، ولو كُتبت القاعدةُ في كلٍّ منها لاختلفت في
   الثالثةِ ونُسيت في الرابعة عشرةَ حين تُضاف.

   ═══ وفي ١٩ أكتوبر ٢٠٢٦ قال الأب: «شِلّ جميع اختبارات الفتري عندهم»
   فنُزعت الثلاثةَ عشرَ إلّا موضعًا واحدًا: اختبارُ مذكّرةِ حسنٍ في
   العلوم — وهو أربعةٌ وعشرون بندًا، فالقُصاصةُ فيه أرجحُ لا أندر.
   ويبقى الاسمُ على حالِه لأنّ الصفوفَ المحفوظةَ تحمل sect:"fatri"،
   وتغييرُه يقطع قراءةَ تقريرِ الأبِ لما مضى. */
(function(g){
  var MIN = 3;                      /* أقلُّ ما يُحسَب درجةً */

  function assign(a, b){
    var o = {}, k;
    for(k in a) if(Object.prototype.hasOwnProperty.call(a, k)) o[k] = a[k];
    for(k in b) if(Object.prototype.hasOwnProperty.call(b, k)) o[k] = b[k];
    return o;
  }

  g.FATRI = {
    MIN: MIN,
    /* o = { got, markTotal, answered, items, essay, done, meta }
       تُرجع { got, total, meta } تُمرَّر إلى saveScore كما هي. */
    row: function(o){
      var meta  = o.meta || {},
          items = o.items || 0,
          n     = o.answered || 0,
          essay = o.essay || 0,
          got   = o.got || 0,
          tot   = o.markTotal || 0;

      if(o.done || (items && n >= items))
        return { got: got, total: tot, meta: meta };

      if(n < MIN)
        /* correct/total صفران عمدًا: صفُّ أثرٍ لا درجة. والعددُ الحقيقيُّ
           في answered/right فلا يدخل أيَّ متوسّطٍ ولو سها عنه فلترٌ يومًا. */
        return { got: 0, total: 0,
                 meta: assign(meta, { kind:"activity", sect:"fatri", partial:true,
                                      answered:n, of:items, right:got,
                                      correct:0, total:0 }) };

      /* درجةُ البندِ الواحدِ من بنودِ الاختيار — والمقاليّاتُ خارجَها،
         فمن لم يبلغها لا يُحاسَب عليها. */
      var per = items ? ((tot - essay) / items) : 0;
      var part = Math.max(got, Math.round(per * n), 1);
      return { got: got, total: part,
               meta: assign(meta, { partial:true, answered:n, of:items }) };
    }
  };
})(window);
