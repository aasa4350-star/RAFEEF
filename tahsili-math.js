function cx(c, v){ v=v||"x"; var a=Math.abs(c); return (a===1?"":a)+v; }
/* cxs — الحدُّ الرئيسُ بإشارته («−5x²» لا «5x²»). تُستخدَم حيث لا
   تسبقها sgn، وإلّا ضاعت الإشارةُ فخالف متنُ السؤالِ جوابَه. */
function cxs(c, v){ v=v||"x"; var a=Math.abs(c); return (c<0?"−":"")+(a===1?"":a)+v; }
function sgn(c){ return c<0 ? "− " : "+ "; }
/* P — نضع السالبَ بين قوسين داخل الشروح، فلا يُقرأ «3 − −48» */
function P(n){ return n<0 ? "("+S(n)+")" : String(n); }
