function ri(a,b){ return Math.floor(Math.random()*(b-a+1))+a; }
function gp(a){ return a[Math.floor(Math.random()*a.length)]; }
function shuf(a){ for(var i=a.length-1;i>0;i--){ var j=Math.floor(Math.random()*(i+1)); var t=a[i]; a[i]=a[j]; a[j]=t; } return a; }
function nz(a,b){ var v=ri(a,b); return v===0 ? nz(a,b) : v; }          /* غير صفر */
function gcd(a,b){ a=Math.abs(a); b=Math.abs(b); while(b){ var t=b; b=a%b; a=t; } return a||1; }
function S(n){ return String(n).replace(/-/g,"−"); }                     /* سالبٌ يُعرَض ناقصًا حقيقيًّا */
function frac(n,d){ if(d<0){ n=-n; d=-d; } var g=gcd(n,d); n/=g; d/=g; return d===1 ? S(n) : (n<0?"−":"")+Math.abs(n)+"/"+d; }
