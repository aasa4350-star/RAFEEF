/* opt4 — أربعةُ خيارٍ متمايزة، الصحيحُ أوّلًا.
   لو تكرّر مشوّشٌ مع الصحيح أو مع غيره أُسقِط، ولو نقص العدد
   أُرجِع null فيتجاهل المولّدَ طالبُه ويعيد المحاولة — وهذا أسلم
   من إخراج سؤالٍ له جوابان (وهي العلّة التي أوقعتني في درس القيمة
   المنزليّة عند أسامة، فصرتُ أرجع null ولا أُصلح بالقوّة). */
function opt4(correct, ds){
  var out=[String(correct)], seen={}; seen[String(correct)]=1;
  for(var i=0;i<ds.length && out.length<4;i++){
    var k=String(ds[i]);
    if(k==="undefined"||k==="null"||k==="NaN"||k===""||seen[k]) continue;
    seen[k]=1; out.push(k);
  }
  return out.length===4 ? out : null;
}
