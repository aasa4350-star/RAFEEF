var SUPN={1:'',2:'²',3:'³',4:'⁴',5:'⁵',6:'⁶',7:'⁷',8:'⁸'};
function pw(c,n){ /* حدُّ cx^n — وn=1 تُكتَب «x» لا «x^1» */
  if(n===0) return S(c);
  var sup = (n===1) ? '' : (SUPN[n] || ('^'+n));
  return (Math.abs(c)===1?(c<0?'−':''):S(c))+'x'+sup;
}
function gDeriv(){
  var n=ri(2,6), c=nz(-7,7), m=ri(1,n-1), c2=nz(-7,7), c0=nz(-9,9);
  var d1=c*n, d2=c2*m;
  return Q('أوجد f ′(x) إذا كانت f(x) = '+pw(c,n)+' '+sgn(c2)+pw(Math.abs(c2),m)+' '+sgn(c0)+Math.abs(c0),
    pw(d1,n-1)+' '+sgn(d2)+pw(Math.abs(d2),m-1),
    [pw(c,n-1)+' '+sgn(c2)+pw(Math.abs(c2),m-1),
     pw(d1,n)+' '+sgn(d2)+pw(Math.abs(d2),m),
     pw(d1,n-1)+' '+sgn(d2)+pw(Math.abs(d2),m-1)+' '+sgn(c0)+Math.abs(c0)],
    'قاعدةُ القوّة: مشتقّةُ cxⁿ هي c·n·x^(ن−1)، ومشتقّةُ الثابت صفر ⇐ '+pw(d1,n-1)+' '+sgn(d2)+pw(Math.abs(d2),m-1)+'.');
}
